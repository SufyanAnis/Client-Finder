// Generates content/index.js from the files in content/<type>/*.js, so adding a
// page is just adding a file. Runs automatically before `next build` / `next dev`.
// Order: the PREFERRED lists below first (in that order), then anything else A–Z.

import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "content");

const PREFERRED = {
  guides: [
    "how-to-find-clients-as-a-freelancer", "cold-email-that-gets-replies", "buying-signals", "ideal-client-profile",
    "linkedin-outreach-for-freelancers", "whatsapp-business-outreach", "follow-up-emails", "cold-outreach-laws",
    "lead-qualification", "find-business-contact-details", "job-posts-as-leads", "track-leads-in-a-spreadsheet",
  ],
  professions: [
    "web-developers", "web-designers", "mobile-app-developers", "seo-consultants", "graphic-designers", "copywriters",
    "video-editors", "social-media-managers", "ux-designers", "marketing-agencies", "bookkeepers", "ai-automation-consultants",
  ],
  templates: [],
  blog: [
    "get-your-first-freelance-client", "how-much-to-charge-as-a-freelancer", "upwork-alternatives",
    "find-international-clients", "cold-email-subject-lines", "cold-email-deliverability",
  ],
  glossary: [],
};

const ident = (type, slug) =>
  type + "_" + slug.replace(/[^a-z0-9]+/gi, "_");

let out = "// GENERATED by scripts/gen-content-index.mjs — do not edit by hand.\n// Add a page by creating content/<type>/<slug>.js (see CONTENT_SPEC.md / BLOG_SPEC.md).\n\n";
const lists = {};
for (const type of Object.keys(PREFERRED)) {
  const dir = join(root, type);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)) : [];
  const pref = PREFERRED[type].filter((s) => files.includes(s));
  const rest = files.filter((s) => !pref.includes(s)).sort();
  lists[type] = [...pref, ...rest];
  for (const s of lists[type]) out += `import ${ident(type, s)} from "./${type}/${s}.js";\n`;
}
out += "\n";
for (const type of Object.keys(lists)) {
  out += `export const ${type} = [${lists[type].map((s) => ident(type, s)).join(", ")}];\n`;
}
out += `
const bySlug = (list) => Object.fromEntries(list.map((x) => [x.slug, x]));
const MAPS = { guides: bySlug(guides), professions: bySlug(professions), templates: bySlug(templates), blog: bySlug(blog), glossary: bySlug(glossary) };

export const getGuide = (s) => MAPS.guides[s] || null;
export const getProfession = (s) => MAPS.professions[s] || null;
export const getTemplate = (s) => MAPS.templates[s] || null;
export const getPost = (s) => MAPS.blog[s] || null;
export const getTerm = (s) => MAPS.glossary[s] || null;

// Resolve a related-slugs object into real items, silently dropping unknown slugs.
export function resolveRelated(rel = {}) {
  const pick = (type) => (rel[type] || []).map((s) => MAPS[type][s]).filter(Boolean);
  return { guides: pick("guides"), templates: pick("templates"), professions: pick("professions"), blog: pick("blog"), glossary: pick("glossary") };
}

export const BLOG_CATEGORIES = [
  { slug: "getting-clients", name: "Getting clients" },
  { slug: "cold-outreach", name: "Cold outreach" },
  { slug: "pricing-and-proposals", name: "Pricing & proposals" },
  { slug: "growing-your-business", name: "Growing your business" },
];

export const CONTENT_UPDATED = "2026-10-03";
`;

writeFileSync(join(root, "index.js"), out);
console.log("content index:", Object.entries(lists).map(([k, v]) => `${k}=${v.length}`).join(" "));
